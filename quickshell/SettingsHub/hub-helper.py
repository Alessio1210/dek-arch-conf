#!/usr/bin/env python3
"""Apply local Quickshell palettes and paired desktop themes with rollback."""
import importlib.util
import colorsys
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
HOME = Path.home()
STATE = HOME / ".config/quickshell/state"
BASELINE = STATE / "original-desktop.json"
TARGETS = [".config/rofi/colors.rasi", ".config/hypr/hyprlock-colors.conf",
           ".config/hypr/swaync-style.css", ".config/ghostty/ghostty-theme",
           ".config/quickshell/state/desktop-theme.lua", ".config/quickshell/state/palette.json"]


def atomic_write(path, text):
    if path.is_symlink():
        path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as f:
        f.write(text)
        temporary = f.name
    os.replace(temporary, path)


def file_snapshot():
    return {name: (HOME / name).read_text() if (HOME / name).is_file() else None for name in TARGETS}


def restore_files(files):
    for name, content in files.items():
        path = HOME / name
        if content is None:
            path.unlink(missing_ok=True)
        else:
            atomic_write(path, content)


def current_wallpaper():
    path = Path(os.environ.get("XDG_STATE_HOME", HOME / ".local/state")) / "hyprquickpaper/current.json"
    try:
        return json.loads(path.read_text())["path"]
    except (FileNotFoundError, KeyError, ValueError):
        return str(HOME / "Pictures/Wallpapers/wallpaper-red.png")


def wallpaper_service():
    spec = importlib.util.spec_from_file_location("wallpaper", ROOT.parent / "hyprquickpaper/helper.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(args):
    try:
        return subprocess.run(args, capture_output=True, text=True, timeout=8)
    except (OSError, subprocess.TimeoutExpired):
        return None


def reload_clients():
    lua = STATE / "desktop-theme.lua"
    if lua.exists():
        result = run(["hyprctl", "eval", lua.read_text()])
        if result is None or result.returncode:
            raise RuntimeError("Hyprland konnte die Theme-Fensterfarben nicht übernehmen.")
    else:
        run(["hyprctl", "reload"])
    run(["timeout", "2", "swaync-client", "-rs"])
    # Ghostty's documented Linux reload signal; this does not close terminals.
    run(["pkill", "-USR2", "-x", "ghostty"])


def generated_files(data):
    c = data["colors"]
    raw = lambda name: c[name].lstrip("#")[-6:]
    bg, fg, muted, accent = (raw(name) for name in ("raised", "text", "muted", "accent"))
    green, blue, line = (raw(name) for name in ("green", "blue", "line"))
    danger = c.get("danger", "#e88d92").lstrip("#")
    files = {}
    props = {"bg": "#" + bg + "d9", "border-color": "#" + accent,
             "bg-alt": "#" + bg + "00", "bg-hover": c["hover"], "bg-selected": "#" + accent + "22",
             "fg": "#" + fg, "fg-muted": "#" + muted, "fg-dark": "#" + bg,
             "fg-selected": "#" + fg, "accent": "#" + accent,
             "accent-soft": "#" + accent + "33", "urgent": "#" + danger}
    files[TARGETS[0]] = "/* Generated by the local Quickshell theme picker. */\n* {\n" + "".join(f"    {k}: {v};\n" for k, v in props.items()) + "}\n"
    lock = {"outline": accent + "aa", "check": green + "aa", "fail": danger + "aa",
            "font": fg + "ff", "date": muted + "cc", "media": fg + "ff", "password": fg + "ff",
            "time": fg + "ff", "layout": muted + "ff"}
    files[TARGETS[1]] = "# Generated by the local Quickshell theme picker.\n" + "".join(f"$lock_{k} = rgba({v})\n" for k, v in lock.items())
    css = (HOME / TARGETS[2]).read_text()
    for key, value in {"bg": "#" + bg, "panel": c["raised"], "panel-alt": c["hover"], "border": "#" + line,
                       "text": c["text"], "muted": c["muted"], "accent": c["accent"], "danger": "#" + danger}.items():
        css = re.sub(r"(@define-color\s+" + re.escape(key) + r"\s+)[^;]+;", lambda m: m[1] + value + ";", css)
    files[TARGETS[2]] = css
    terminal = (HOME / TARGETS[3]).read_text()
    for key, value in {"background": "#" + bg, "foreground": c["text"], "cursor-color": c["accent"],
                       "selection-background": c["hover"], "selection-foreground": c["text"]}.items():
        terminal = re.sub(r"^" + re.escape(key) + r"\s*=.*$", key + " = " + value, terminal, flags=re.M)
    ansi = [bg, danger, green, "d9c898", blue, "b9a4cf", accent, fg,
            line, "f0a3a8", "a9d9bd", "e9d8ac", "b0d1df", "cbbadd", "c2e6d6", "f3f6f2"]
    for i, value in enumerate(ansi):
        terminal = re.sub(r"^(palette\s*=\s*" + str(i) + r"=).*$", lambda m: m[1] + "#" + value, terminal, flags=re.M)
    files[TARGETS[3]] = terminal
    files[TARGETS[4]] = 'hl.config({ general = { col = { active_border = "rgb(' + accent + ')", inactive_border = "rgb(' + line + ')" } } })\n'
    return files


def validate_theme(identifier):
    if Path(identifier).name != identifier or identifier.startswith("."):
        raise ValueError("Ungültiger Theme-Name")
    data = json.loads((ROOT / "themes" / (identifier + ".json")).read_text())
    if not all(isinstance(v, str) and re.fullmatch(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", v) for v in data["colors"].values()):
        raise ValueError("Ungültige Farbe")
    return data


def list_themes():
    result = []
    for path in sorted((ROOT / "themes").glob("*.json")):
        data = json.loads(path.read_text())
        if data.get("desktop") and data.get("wallpaper"):
            result.append(dict(data, id=path.stem))
    return result


def theme_for_wallpaper(value):
    """Keep authored palettes; create a full desktop theme for each new image."""
    from PIL import Image, ImageOps
    path = Path(os.path.expandvars(os.path.expanduser(str(value)))).resolve()
    signature = f"{path.stat().st_mtime_ns}:{path.stat().st_size}"
    for theme in list_themes():
        candidate = Path(os.path.expandvars(os.path.expanduser(theme["wallpaper"]))).resolve()
        if candidate == path and (not theme.get("automatic") or theme.get("image_signature") == signature):
            return theme
    with Image.open(path) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        image.thumbnail((96, 96))
        palette = image.quantize(colors=12).convert("RGB").getcolors(96 * 96)
    def score(item):
        count, rgb = item
        hue, light, saturation = colorsys.rgb_to_hls(*(x / 255 for x in rgb))
        return count * (0.2 + saturation) * (1 if 0.12 < light < 0.88 else 0.1)
    rgb = max(palette, key=score)[1]
    hue, _, saturation = colorsys.rgb_to_hls(*(x / 255 for x in rgb))
    saturation = max(0.18, min(0.48, saturation))
    def color(light, sat=None, shift=0):
        values = colorsys.hls_to_rgb((hue + shift) % 1, light, saturation if sat is None else sat)
        return "#" + "".join(f"{round(x * 255):02x}" for x in values)
    identifier = "auto-" + hashlib.sha256(str(path).encode()).hexdigest()[:12]
    data = {"name": path.stem, "desktop": True, "automatic": True,
            "wallpaper": str(path), "image_signature": signature,
            "colors": {"surface": "#ed" + color(0.065, 0.2)[1:],
                       "raised": color(0.065, 0.2), "hover": color(0.15, 0.2),
                       "line": color(0.25, 0.2), "text": color(0.91, 0.12),
                       "muted": color(0.64, 0.12), "accent": color(0.73),
                       "green": color(0.7, 0.24, 0.05), "blue": color(0.73, 0.25, 0.14),
                       "danger": "#df9291"}}
    atomic_write(ROOT / "themes" / (identifier + ".json"), json.dumps(data, indent=2, ensure_ascii=False))
    return dict(data, id=identifier)


def apply_theme(identifier):
    data = validate_theme(identifier)
    STATE.mkdir(parents=True, exist_ok=True)
    if not data.get("desktop"):
        raise ValueError("Dieses Theme benötigt einen Hintergrund für einen vollständigen Desktop-Wechsel.")
    before = {"files": file_snapshot(), "wallpaper": current_wallpaper()}
    if not BASELINE.exists():
        atomic_write(BASELINE, json.dumps(before, ensure_ascii=False, indent=2))
    wallpaper = os.path.expanduser(os.path.expandvars(data["wallpaper"]))
    if not Path(wallpaper).is_file():
        raise ValueError("Das Wallpaper zu diesem Theme fehlt.")
    if data.get("restore_original"):
        target = json.loads(BASELINE.read_text())
        files = target["files"]
    else:
        files = generated_files(data)
        files[TARGETS[-1]] = json.dumps(dict(data["colors"], _preset=identifier))
    service = wallpaper_service()
    try:
        service.apply_wallpaper(wallpaper)
        restore_files(files)
        reload_clients()
    except Exception:
        restore_files(before["files"])
        try:
            service.apply_wallpaper(before["wallpaper"])
            reload_clients()
        except Exception:
            pass
        raise


if __name__ == "__main__":
    try:
        if sys.argv[1] == "list":
            print(json.dumps(list_themes()))
        elif sys.argv[1] == "theme":
            apply_theme(sys.argv[2])
            print('{"ok":true}')
        else:
            raise ValueError("Unbekannte Aktion")
    except Exception as error:
        print(json.dumps({"error": str(error)}))
        sys.exit(1)
